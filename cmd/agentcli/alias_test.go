func TestConfigSetWritesTokenForNonDefaultServer(t *testing.T) {
	home := aliasTestEnv(t)
	if res := runAliasCLIStdin(t, "def\n", "config", "set", "--server", "https://default.dev", "--token-stdin", "--default"); res.err != nil {
		t.Fatalf("config set default error = %v", res.err)
	}
	// Unrelated config must survive a `config set`.
	cfg, err := loadConfig()
	if err != nil {
		t.Fatalf("loadConfig error = %v", err)
	}
	cfg.ProjectBindings = []projectBinding{{Server: "https://default.dev", RemoteDir: "/r", LocalPath: "/l"}}
	cfg.RememberedFlags = map[string][]string{"edit": {"--editor=cat"}}
	if err := saveConfig(cfg); err != nil {
		t.Fatalf("saveConfig error = %v", err)
	}

	res := runAliasCLIStdin(t, "other-token\n", "config", "set", "--server", "https://other.dev", "--token-stdin")
	if res.err != nil {
		t.Fatalf("config set error = %v (stderr=%s)", res.err, res.stderr)
	}
	requireContains(t, res.stdout, "domain added: https://other.dev", "stdout")
	requireContains(t, res.stdout, "token set for https://other.dev", "stdout")
	if strings.Contains(res.stdout, "other-token") {
		t.Fatal("config set must never echo the token")
	}

	cfg, err = loadConfig()
	if err != nil {
		t.Fatalf("loadConfig error = %v", err)
	}
	if cfg.Default != "https://default.dev" {
		t.Fatalf("default = %q, want unchanged https://default.dev", cfg.Default)
	}
	other := cfg.FindDomain("https://other.dev")
	if other == nil || other.Token != "other-token" {
		t.Fatalf("other domain = %+v, want token other-token", other)
	}
	if len(cfg.ProjectBindings) != 1 || cfg.RememberedFlags["edit"][0] != "--editor=cat" {
		t.Fatalf("config set dropped unrelated config: %+v", cfg)
	}
	data, err := os.ReadFile(filepath.Join(home, ".ai-critic", "remote-agent-config.json"))
	if err != nil {
		t.Fatalf("read config error = %v", err)
	}
	if !strings.Contains(string(data), "other-token") {
		t.Fatal("token was not persisted")
	}
}

