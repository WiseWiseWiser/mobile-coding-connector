// aliasTestEnv gives a test its own HOME plus a fake `remote-agent` on PATH so
// wrapper resolution is deterministic (never the real user's binaries).
func aliasTestEnv(t *testing.T) (home string) {
	t.Helper()
	home = t.TempDir()
	testhooks.SetHomeOverride(home)
	t.Cleanup(testhooks.ResetInProcessOverrides)

	binDir := filepath.Join(t.TempDir(), "path-bin")
	if err := os.MkdirAll(binDir, 0755); err != nil {
		t.Fatalf("MkdirAll(%s) error = %v", binDir, err)
	}
	fake := filepath.Join(binDir, "remote-agent")
	if err := os.WriteFile(fake, []byte("#!/bin/sh\nexit 0\n"), 0755); err != nil {
		t.Fatalf("write fake remote-agent error = %v", err)
	}
	t.Setenv("PATH", binDir)
	return home
}

type aliasCLIResult struct {
	stdout string
	stderr string
	err    error
}

func runAliasCLI(t *testing.T, args ...string) aliasCLIResult {
	t.Helper()
	return runAliasCLIStdin(t, "", args...)
}

// runAliasCLIStdin runs the CLI in-process with an optional stdin payload
// (used by `config set --token-stdin`).
func runAliasCLIStdin(t *testing.T, stdin string, args ...string) aliasCLIResult {
	t.Helper()
	var stdout, stderr bytes.Buffer

	oldStdin := os.Stdin
	if stdin != "" || hasArg(args, "--token-stdin") {
		r, w, err := os.Pipe()
		if err != nil {
			t.Fatalf("os.Pipe() error = %v", err)
		}
		if _, err := w.WriteString(stdin); err != nil {
			t.Fatalf("write stdin error = %v", err)
		}
		w.Close()
		os.Stdin = r
		defer func() {
			os.Stdin = oldStdin
			r.Close()
		}()
	}

	err := RunWithWriters(RemoteProfile(), args, &stdout, &stderr)
	return aliasCLIResult{stdout: stdout.String(), stderr: stderr.String(), err: err}
}

func hasArg(args []string, name string) bool {
	for _, a := range args {
		if a == name || strings.HasPrefix(a, name+"=") {
			return true
		}
	}
	return false
}

func readAliasStoreFile(t *testing.T, home string) aliasStore {
	t.Helper()
	data, err := os.ReadFile(filepath.Join(home, ".ai-critic", "remote-agent-aliases.json"))
	if err != nil {
		t.Fatalf("read alias store error = %v", err)
	}
	var st aliasStore
	if err := json.Unmarshal(data, &st); err != nil {
		t.Fatalf("parse alias store error = %v", err)
	}
	return st
}

func readWrapper(t *testing.T, home, name string) string {
	t.Helper()
	data, err := os.ReadFile(filepath.Join(home, ".local", "bin", name))
	if err != nil {
		t.Fatalf("read wrapper %s error = %v", name, err)
	}
	return string(data)
}

func requireContains(t *testing.T, got, want, label string) {
	t.Helper()
	if !strings.Contains(got, want) {
		t.Fatalf("%s missing %q\ngot:\n%s", label, want, got)
	}
}

func requireNoFile(t *testing.T, path string) {
	t.Helper()
	if _, err := os.Stat(path); !os.IsNotExist(err) {
		t.Fatalf("%s should not exist (stat error = %v)", path, err)
	}
}

func TestAliasAddInstallsWrapperAndStore(t *testing.T) {
	home := aliasTestEnv(t)

	res := runAliasCLI(t, "alias", "add", "xdev", "--server", "https://x.dev/")
	if res.err != nil {
		t.Fatalf("alias add error = %v (stderr=%s)", res.err, res.stderr)
	}
	requireContains(t, res.stdout, "installed ~/.local/bin/xdev-agent (alias xdev → https://x.dev)", "stdout")
	requireContains(t, res.stderr, "warning: no token saved for https://x.dev", "stderr")
	requireContains(t, res.stderr, "xdev-agent config set --token-stdin", "stderr hint")

	wrapperPath := filepath.Join(home, ".local", "bin", "xdev-agent")
	info, err := os.Stat(wrapperPath)
	if err != nil {
		t.Fatalf("stat wrapper error = %v", err)
	}
	if info.Mode().Perm() != 0755 {
		t.Fatalf("wrapper mode = %v, want 0755", info.Mode().Perm())
	}
	wantBody := "#!/bin/sh\n" +
		"# generated by remote-agent alias install (alias: xdev); do not edit\n" +
		"exec remote-agent --alias xdev \"$@\"\n"
	if got := readWrapper(t, home, "xdev-agent"); got != wantBody {
		t.Fatalf("wrapper body = %q, want %q", got, wantBody)
	}

	st := readAliasStoreFile(t, home)
	if len(st.Aliases) != 1 {
		t.Fatalf("aliases = %+v, want 1 entry", st.Aliases)
	}
	if got := st.Aliases[0]; got.Name != "xdev" || got.Binary != "xdev-agent" || got.Server != "https://x.dev" {
		t.Fatalf("alias entry = %+v, want normalized server https://x.dev", got)
	}
}

