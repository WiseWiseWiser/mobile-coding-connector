// aliasPingServer counts requests and answers /ping, so tests can prove which
// server a command targeted.
type aliasPingServer struct {
	*httptest.Server
	hits atomic.Int64
}

func newAliasPingServer(t *testing.T, name string) *aliasPingServer {
	t.Helper()
	s := &aliasPingServer{}
	s.Server = httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		s.hits.Add(1)
		if r.URL.Path != "/ping" {
			http.NotFound(w, r)
			return
		}
		w.Write([]byte("pong"))
	}))
	t.Cleanup(s.Close)
	return s
}

func TestAliasFlagTargetsAliasServer(t *testing.T) {
	aliasTestEnv(t)
	def := newAliasPingServer(t, "default")
	aliased := newAliasPingServer(t, "xdev")

	if res := runAliasCLIStdin(t, "def-token\n", "config", "set", "--server", def.URL, "--token-stdin", "--default"); res.err != nil {
		t.Fatalf("config set default error = %v (stderr=%s)", res.err, res.stderr)
	}
	if res := runAliasCLIStdin(t, "xdev-token\n", "config", "set", "--server", aliased.URL, "--token-stdin"); res.err != nil {
		t.Fatalf("config set alias server error = %v", res.err)
	}
	if res := runAliasCLI(t, "alias", "add", "xdev", "--server", aliased.URL); res.err != nil {
		t.Fatalf("alias add error = %v (stderr=%s)", res.err, res.stderr)
	}

	res := runAliasCLI(t, "ping")
	if res.err != nil {
		t.Fatalf("plain ping error = %v", res.err)
	}
	if def.hits.Load() != 1 || aliased.hits.Load() != 0 {
		t.Fatalf("plain ping hits: default=%d aliased=%d, want 1/0", def.hits.Load(), aliased.hits.Load())
	}

	res = runAliasCLI(t, "--alias", "xdev", "ping")
	if res.err != nil {
		t.Fatalf("alias ping error = %v", res.err)
	}
	if def.hits.Load() != 1 || aliased.hits.Load() != 1 {
		t.Fatalf("alias ping hits: default=%d aliased=%d, want 1/1", def.hits.Load(), aliased.hits.Load())
	}
	requireContains(t, res.stdout, aliased.URL, "alias ping stdout")

	res = runAliasCLI(t, "--alias", "nope", "ping")
	if res.err == nil {
		t.Fatal("unknown alias should fail")
	}
	requireContains(t, res.err.Error(), `unknown alias "nope" (available: xdev)`, "error")
}

